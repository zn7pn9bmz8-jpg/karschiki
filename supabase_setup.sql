-- Выполнить целиком в Supabase: SQL Editor -> New query -> Run.
-- Для небольшого закрытого круга друзей включён публичный доступ по ссылке.
-- Важно: это дружеский рейтинг, а не защищённая от накрутки турнирная система.

create table if not exists public.players (
  player_id text primary key,
  player_name text not null check (char_length(player_name) between 2 and 24),
  created_at timestamptz not null default now()
);

create table if not exists public.game_rounds (
  id bigint generated by default as identity primary key,
  player_id text not null,
  player_name text not null,
  multiplier numeric(10,2) not null check (multiplier >= 1 and multiplier <= 100000),
  collected boolean not null default false,
  bet_amount integer not null default 300 check (bet_amount > 0),
  earned integer not null default 0 check (earned >= 0),
  created_at timestamptz not null default now()
);

-- Миграция для таблицы, если она была создана предыдущей версией.
alter table public.game_rounds add column if not exists bet_amount integer not null default 300;
alter table public.game_rounds add column if not exists earned integer not null default 0;

create index if not exists game_rounds_created_at_idx on public.game_rounds (created_at desc);
create index if not exists game_rounds_player_id_idx on public.game_rounds (player_id);

alter table public.players enable row level security;
alter table public.game_rounds enable row level security;

grant select, insert, update on public.players to anon, authenticated;
grant select, insert on public.game_rounds to anon, authenticated;

drop policy if exists "Anyone can view players" on public.players;
create policy "Anyone can view players" on public.players for select to anon, authenticated using (true);
drop policy if exists "Anyone can join players" on public.players;
create policy "Anyone can join players" on public.players for insert to anon, authenticated with check (true);
drop policy if exists "Anyone can update player names" on public.players;
create policy "Anyone can update player names" on public.players for update to anon, authenticated using (true) with check (true);

drop policy if exists "Anyone can view game rounds" on public.game_rounds;
create policy "Anyone can view game rounds" on public.game_rounds for select to anon, authenticated using (true);
drop policy if exists "Anyone can submit game rounds" on public.game_rounds;
create policy "Anyone can submit game rounds" on public.game_rounds for insert to anon, authenticated with check (true);
